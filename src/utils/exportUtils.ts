import { EvaluationResults, HistoryRecord, DatasetItem } from '../types';

/**
 * Downloads a string content as a client-side file
 */
export function downloadFile(content: string, filename: string, mimeType: string = 'text/plain;charset=utf-8;') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generates and downloads a CSV export for model evaluation results
 */
export function exportResultsAsCSV(results: EvaluationResults) {
  const rows = [
    ['Q-Health AI Model Evaluation Results (Demo Export)'],
    ['Generated At', results.executedAt],
    ['Dataset', results.datasetName],
    ['Model Architecture', results.modelName],
    ['Demo Notice', 'Simulated Research Demonstration Data'],
    [],
    ['Core Metric', 'Score (%)'],
    ['Accuracy', `${results.accuracy}%`],
    ['Precision', `${results.precision}%`],
    ['Recall', `${results.recall}%`],
    ['F1-Score', `${results.f1Score}%`],
    ['Circuit Depth', results.quantumDepth],
    ['Qubit Fidelity', `${results.qubitFidelity}%`],
    ['Execution Latency', `${results.runtimeSeconds}s`],
    ['Test Samples Count', results.testSamples],
    [],
    ['Confusion Matrix', 'Value'],
    ['True Positive (TP)', results.confusionMatrix.tp],
    ['False Positive (FP)', results.confusionMatrix.fp],
    ['False Negative (FN)', results.confusionMatrix.fn],
    ['True Negative (TN)', results.confusionMatrix.tn],
    [],
    ['Benchmark Comparison', 'QSVC (%)', 'Classical SVM (%)', 'Random Forest (%)'],
    ...results.benchmarkComparison.map(b => [b.metric, `${b.qsvc}%`, `${b.classicalSvm}%`, `${b.randomForest}%`]),
    [],
    ['Feature Importance', 'Relative Weight', 'Quantum Amplitude'],
    ...results.featureImportance.map(f => [f.feature, f.importance, f.quantumWeight])
  ];

  const csvContent = rows.map(e => e.map(item => `"${String(item).replace(/"/g, '""')}"`).join(',')).join('\n');
  downloadFile(csvContent, `QHealth_AI_Results_${results.datasetName.replace(/\s+/g, '_')}.csv`, 'text/csv;charset=utf-8;');
}

