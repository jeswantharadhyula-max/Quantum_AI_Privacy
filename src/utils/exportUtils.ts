/**
 * Downloads a sample dataset as a CSV
 */
export function exportSampleDatasetCSV(dataset: DatasetItem) {
  if (!dataset.columns || dataset.columns.length === 0) return;

  const header = dataset.columns.map(c => c.name);
  const rows = dataset.sampleRows.map(row => {
    return header.map(col => row[col] !== undefined ? String(row[col]) : '').join(',');
  });

  const csvContent = [header.join(','), ...rows].join('\n');
  downloadFile(csvContent, `${dataset.id}_sample.csv`, 'text/csv;charset=utf-8;');
}

/**
 * Exports all history records to CSV
 */
export function exportHistoryCSV(history: HistoryRecord[]) {
  const header = ['ID', 'Dataset Name', 'Model Architecture', 'Timestamp', 'Status', 'Duration', 'Accuracy (%)', 'F1 Score (%)', 'Privacy Epsilon'];
  const rows = history.map(h => [
    h.id,
    `"${h.datasetName}"`,
    `"${h.modelName}"`,
    `"${h.timestamp}"`,
    h.status,
    h.duration,
    h.accuracy,
    h.f1Score,
    h.privacyEpsilon
  ].join(','));

  const csvContent = [header.join(','), ...rows].join('\n');
  downloadFile(csvContent, `QHealth_Analysis_History_${Date.now()}.csv`, 'text/csv;charset=utf-8;');
}
